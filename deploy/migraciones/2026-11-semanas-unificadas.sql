-- Semanas unificadas: Planificacion -> DiaPlan -> EjercicioPlanificado -> PrescripcionSemanal
--
-- ANTES DE CORRERLO: backup completo de la base, y backend frenado.
--   docker compose exec -T db pg_dump -U "$DB_USERNAME" -d masgym -Fc > backups/antes-semanas-unificadas.dump
--   docker compose stop backend
--   docker compose exec -T db psql -U "$DB_USERNAME" -d masgym -v ON_ERROR_STOP=1 < deploy/migraciones/2026-11-semanas-unificadas.sql
--
-- Toma la Semana 1 de cada plan como base (dias + ejercicios) y crea una
-- PrescripcionSemanal por semana, emparejando dias por nombre ("Dia 1") y
-- ejercicios por orden dentro del dia + mismo ejercicio. Si en algun plan las
-- semanas no coinciden, NO adivina: aborta y lista los casos para revisarlos a mano.
-- Todo corre en una sola transaccion: si algo falla, la base queda como estaba.

BEGIN;

-- Semanas numeradas 1..N por plan (por si los numeros tienen huecos, ej. 1,2,4)
CREATE TEMP TABLE semanas_num ON COMMIT DROP AS
  SELECT s.id, s.planificacion_id,
         row_number() OVER (PARTITION BY s.planificacion_id ORDER BY s.numero_semana, s.id) AS n
  FROM semanas_plan s;

-- Semana 1 de cada plan: dia + orden + ejercicio
CREATE TEMP TABLE base ON COMMIT DROP AS
  SELECT sn.planificacion_id, d.id AS dia_id, d.dia_semana, e.id AS ep_id, e.orden, e.ejercicio_id
  FROM semanas_num sn
  JOIN dias_plan d ON d.semana_plan_id = sn.id
  LEFT JOIN ejercicios_planificados e ON e.dia_plan_id = d.id
  WHERE sn.n = 1;

-- Semanas 2..N con el mismo formato que "base"
CREATE TEMP TABLE resto ON COMMIT DROP AS
  SELECT sn.planificacion_id, sn.n, d.dia_semana, e.orden, e.ejercicio_id
  FROM semanas_num sn
  JOIN dias_plan d ON d.semana_plan_id = sn.id
  LEFT JOIN ejercicios_planificados e ON e.dia_plan_id = d.id
  WHERE sn.n > 1;

-- 0) Reporte de inconsistencias
CREATE TEMP TABLE reporte ON COMMIT DROP AS
  SELECT planificacion_id, 'tiene ' || count(*) || ' semanas (maximo 5)' AS problema
  FROM semanas_num GROUP BY planificacion_id HAVING count(*) > 5
  UNION ALL
  SELECT sn.planificacion_id, 'semana ' || sn.n || ': "' || d.dia_semana || '" esta repetido'
  FROM semanas_num sn JOIN dias_plan d ON d.semana_plan_id = sn.id
  GROUP BY sn.planificacion_id, sn.n, d.dia_semana HAVING count(*) > 1
  UNION ALL
  SELECT sn.planificacion_id, 'semana ' || sn.n || ', ' || d.dia_semana || ': el orden ' || e.orden || ' esta repetido'
  FROM semanas_num sn JOIN dias_plan d ON d.semana_plan_id = sn.id
  JOIN ejercicios_planificados e ON e.dia_plan_id = d.id
  GROUP BY sn.planificacion_id, sn.n, d.dia_semana, e.orden HAVING count(*) > 1
  UNION ALL
  SELECT DISTINCT x.planificacion_id,
         'semana ' || x.n || ' no coincide con la semana 1 en ' || x.dia_semana
         || coalesce(' (orden ' || x.orden || ')', ' (dia sin ejercicios en una de las dos)')
  FROM (
    -- algo que esta en la semana N y no en la semana 1
    (SELECT planificacion_id, n, dia_semana, orden, ejercicio_id FROM resto
     EXCEPT
     SELECT b.planificacion_id, sn.n, b.dia_semana, b.orden, b.ejercicio_id
     FROM base b JOIN semanas_num sn ON sn.planificacion_id = b.planificacion_id AND sn.n > 1)
    UNION
    -- algo que esta en la semana 1 y falta en la semana N
    (SELECT b.planificacion_id, sn.n, b.dia_semana, b.orden, b.ejercicio_id
     FROM base b JOIN semanas_num sn ON sn.planificacion_id = b.planificacion_id AND sn.n > 1
     EXCEPT
     SELECT planificacion_id, n, dia_semana, orden, ejercicio_id FROM resto)
  ) x;

DO $$
DECLARE r text;
BEGIN
  SELECT string_agg('  plan ' || planificacion_id || ': ' || problema, E'\n' ORDER BY planificacion_id, problema)
    INTO r FROM reporte;
  IF r IS NOT NULL THEN
    RAISE EXCEPTION E'Migracion cancelada, no se cambio nada. Revisar a mano:\n%', r;
  END IF;
END $$;

-- 1) Esquema nuevo
ALTER TABLE planificaciones
  ADD COLUMN cantidad_semanas integer NOT NULL DEFAULT 5,
  ADD CONSTRAINT ck_planificaciones_cantidad_semanas CHECK (cantidad_semanas BETWEEN 1 AND 5);

CREATE TABLE prescripciones_semanales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ejercicio_planificado_id bigint NOT NULL
    CONSTRAINT fk_prescripcion_ejercicio_planificado REFERENCES ejercicios_planificados(id) ON DELETE CASCADE,
  numero_semana integer NOT NULL,
  series integer,
  reps varchar(255),
  rir varchar(255),
  notas_peso varchar(255),
  CONSTRAINT uk_prescripcion_ep_semana UNIQUE (ejercicio_planificado_id, numero_semana)
);

ALTER TABLE dias_plan
  ADD COLUMN planificacion_id bigint
    CONSTRAINT fk_dia_plan_planificacion REFERENCES planificaciones(id);

-- 2) Los dias de la Semana 1 pasan a colgar del plan
UPDATE dias_plan d SET planificacion_id = sn.planificacion_id
FROM semanas_num sn
WHERE d.semana_plan_id = sn.id AND sn.n = 1;

-- 3) Una prescripcion por semana, emparejando dia + orden + ejercicio contra la Semana 1.
--    notas y peso_kg se unen en notas_peso ("notas · 40 kg").
INSERT INTO prescripciones_semanales (ejercicio_planificado_id, numero_semana, series, reps, rir, notas_peso)
SELECT b.ep_id, sn.n, e.series, e.repeticiones::text, nullif(trim(e.rir), ''),
       nullif(concat_ws(' · ', nullif(trim(e.notas), ''), e.peso_kg || ' kg'), '')
FROM semanas_num sn
JOIN dias_plan d ON d.semana_plan_id = sn.id
JOIN ejercicios_planificados e ON e.dia_plan_id = d.id
JOIN base b ON b.planificacion_id = sn.planificacion_id
           AND b.dia_semana = d.dia_semana
           AND b.orden = e.orden
           AND b.ejercicio_id = e.ejercicio_id;

-- 4) cantidad_semanas = semanas que tenia (un plan sin semanas queda en 5)
UPDATE planificaciones p SET cantidad_semanas = c.total
FROM (SELECT planificacion_id, count(*) AS total FROM semanas_num GROUP BY planificacion_id) c
WHERE c.planificacion_id = p.id;

-- 5) Borrar las semanas 2..N y las columnas/tablas viejas
DELETE FROM ejercicios_planificados e USING dias_plan d
WHERE e.dia_plan_id = d.id AND d.planificacion_id IS NULL;
DELETE FROM dias_plan WHERE planificacion_id IS NULL;

ALTER TABLE dias_plan
  ALTER COLUMN planificacion_id SET NOT NULL,
  DROP COLUMN semana_plan_id;
ALTER TABLE ejercicios_planificados
  DROP COLUMN series, DROP COLUMN repeticiones, DROP COLUMN peso_kg,
  DROP COLUMN notas, DROP COLUMN rir;
DROP TABLE semanas_plan;

-- 6) Control: cada ejercicio tiene que tener exactamente cantidad_semanas prescripciones
DO $$
DECLARE malos int;
BEGIN
  SELECT count(*) INTO malos
  FROM ejercicios_planificados e
  JOIN dias_plan d ON d.id = e.dia_plan_id
  JOIN planificaciones p ON p.id = d.planificacion_id
  WHERE (SELECT count(*) FROM prescripciones_semanales ps WHERE ps.ejercicio_planificado_id = e.id)
        <> p.cantidad_semanas;
  IF malos > 0 THEN
    RAISE EXCEPTION 'Control fallido: % ejercicios sin todas sus semanas. No se cambio nada.', malos;
  END IF;
END $$;

SELECT (SELECT count(*) FROM planificaciones)          AS planes,
       (SELECT count(*) FROM dias_plan)                AS dias,
       (SELECT count(*) FROM ejercicios_planificados)  AS ejercicios,
       (SELECT count(*) FROM prescripciones_semanales) AS prescripciones;

COMMIT;
